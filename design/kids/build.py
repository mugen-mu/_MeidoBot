RATING = {"g": "G: для любого возраста", "pg": "PG: детям вместе с родителями", "pg_13": "PG-13: с 13 лет"}


def plural(n: int, one: str, few: str, many: str) -> str:
    if 11 <= n % 100 <= 14:
        return many
    return {1: one, 2: few, 3: few, 4: few}.get(n % 10, many)


def fmt(it: dict) -> str:
    d = it["duration"]
    if it["kind"] == "movie":
        return f"Фильм, {d} мин"
    if it["status"] == "ongoing" or not it["episodes"]:
        return f"Сериал с {it['year']} года, серия {d} мин, серий очень много"
    n = it["episodes"]
    return f"{n} {plural(n, 'серия', 'серии', 'серий')} по {d} мин"


def main() -> None:
    titles = json.loads((HERE / "titles.json").read_text(encoding="utf-8"))
    items = []
    for it in titles["items"]:
        tier, why, note = NOTES[it["id"]]
        items.append({
            "id": it["id"], "ru": it["ru"], "orig": it["orig"], "year": it["year"], "format": fmt(it),
            "score": it["score"], "rating": RATING.get(it["rating"], it["rating"]), "tier": tier, "why": why, "note": note,
        })
    assert len(items) == len(NOTES) and {i["tier"] for i in items} == {A, B, C}
    data = json.dumps({"items": items}, ensure_ascii=False).replace("</", "<\\/")
    tpl = (HERE / "template.html").read_text(encoding="utf-8")
    assert tpl.count("/*DATA*/null") == 1
    (HERE / "page.html").write_text(tpl.replace("/*DATA*/null", data), encoding="utf-8")
    print(f"page.html: {len(items)} тайтлов (A {sum(i['tier'] == A for i in items)}, B {sum(i['tier'] == B for i in items)}, C {sum(i['tier'] == C for i in items)})")


if __name__ == "__main__":
    main()
