let w: World;
beforeEach(async () => {
  w = new World();
  await w.seed({ intake: true, settings: { summary_morning: "off", summary_evening: "off", weekly: "off", light: "3" } });
  await w.run(NOW); // первый запуск запоминает конец канала
});

describe("cron: погода текстом в канале «бот»", () => {
  it("«Какой прогноз на завтра?» → честный ответ «погоду не читаю», дело не создаётся, есть кнопка «Это было дело»", async () => {
    w.discord.say(CH_BOT, OWNER, "Какой прогноз на завтра?");
    const r = await w.run(NOW + MINUTE);
    expect(r.intake).toBe(1);
    expect(w.d1.q("SELECT 1 FROM items")).toHaveLength(0);
    const msg = w.discord.live(CH_BOT)[0];
    expect(msg.body.content).toBe(WEATHER_REPLY);
    expect(String(msg.body.content)).toContain("не читаю");
    const ids = (msg.body.components ?? []).flatMap((x) => x.components.map((c) => c.custom_id));
    expect(ids).toEqual(["ldo:Какой прогноз на завтра?"]);
  });

  it("обычное дело про зонт остаётся делом", async () => {
    w.discord.say(CH_BOT, OWNER, "завтра в 10 купить зонт");
    await w.run(NOW + MINUTE);
    expect(w.d1.q("SELECT title FROM items")).toEqual([{ title: "Купить зонт" }]);
  });

  it("чужой человек в канале: ответа нет", async () => {
    w.discord.say(CH_BOT, "555", "какая погода");
    await w.run(NOW + MINUTE);
    expect(w.discord.live(CH_BOT)).toHaveLength(0);
  });
});
