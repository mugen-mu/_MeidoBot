-- Этап 3 ретроспективы 2: хвост «Висит» и автозаморозка.
-- touched_at — когда хозяин в последний раз сам что-то сделал с делом (отложил, поменял время или название): от него считаются
-- «давнее» (больше 7 дней) и заморозка (30 дней без единого нажатия). NULL — касаний не было, считаем от срока.
-- Замороженное дело — обычное срабатывание в состоянии 'cancelled' с closed_reason = 'frozen' (таблицу не пересоздаём: проверка состояний
-- в схеме осталась прежней); оно остаётся в базе, не напоминает, не стирается (scrubOps его пропускает) и возвращается кнопкой «Вернуть».
ALTER TABLE occurrences ADD COLUMN touched_at INTEGER;
CREATE INDEX idx_occ_frozen ON occurrences(closed_at) WHERE state = 'cancelled' AND closed_reason = 'frozen';
