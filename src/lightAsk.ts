// Вопрос про свет обычным текстом в канале «бот» («дай график света», «что со светом»): отвечаем графиком, а не заводим дело.
// Правило до разбора напоминания, без языковой модели (решение пользователя 2026-11-10, этап 1 «C-lite»).
// Осторожность важнее смелости: всё сообщение должно состоять из слов вопроса (список ниже) и содержать слово «свет».
// Любое лишнее слово или цифра (время, дата) — это обычное дело, а не вопрос. Для промаха под ответом есть кнопка «Это было дело».
// Общий разбор — `ask.ts`; формулировки расширены 2026-11-10 по живой проверке («когда дадут свет», «график отключений», «какой график»).
import { ASK_COMMON, ASK_MAX_CHARS, type AskSpec, matchAsk } from "./ask.ts";
import type { MessageBody } from "./discord/types.ts";

/** Самая длинная фраза-вопрос, символов (длиннее — это уже дело или рассказ). */
export const LIGHT_ASK_MAX_CHARS = ASK_MAX_CHARS;

/** Слова, которые допустимы в вопросе рядом со словом «свет» (к общим добавлены про свет и график). */
const FILLER = new Set([
  ...ASK_COMMON,
  "график", "графики", "графика", "графику", "отключений", "отключения", "отключение", "отключат", "отключили", "выключат", "выключили", "включат", "включили",
  "вырубили", "дали", "дадут", "дадите", "пропал", "пропадет", "пропадут", "группе", "моей", "нашей", "неделю", "ближайший", "ближайшие", "часы",
]);

/** «свет» в любой форме: свет, света, свету, светом, свете; «электричество»; «отключение/отключения» (график отключений — тоже про свет). */
const KEY = /^(?:свет(?:а|у|ом|е)?|электричеств(?:о|а|у|ом|е)|отключени(?:е|я|й|ю|ями|ях))$/u;

/** «график» без слова «свет» — вопрос только из пары слов («какой график», «дай график», «график на завтра»): других графиков у бота нет, а «составить график отпусков» — уже дело. */
const SHORT_KEY = { rx: /^график(?:и|а|у)?$/u, maxWords: 4 };

const SPEC: AskSpec = { key: KEY, filler: FILLER, shortKey: SHORT_KEY };

/** Похоже ли сообщение на вопрос «покажи график света». */
export function isLightQuestion(text: string): boolean {
  return matchAsk(text, SPEC);
}

/** Кнопка под ответом: «Это было дело» — исходная фраза записывается как обычное дело (custom_id `ldo:<фраза>`, до 100 знаков в сумме). */
export const LIGHT_ASK_BUTTON_PREFIX = "ldo:";

export function lightAskMessage(text: string, original: string): MessageBody {
  return {
    content: text,
    components: [{ type: 1, components: [{ type: 2, style: 2, label: "Это было дело", custom_id: `${LIGHT_ASK_BUTTON_PREFIX}${original.trim().slice(0, LIGHT_ASK_MAX_CHARS)}` }] }],
    allowed_mentions: { parse: [] },
  };
}
