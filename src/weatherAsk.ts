// Вопрос про погоду обычным текстом в канале «бот» («какой прогноз на завтра?», «будет ли дождь»): ответ вместо дела.
// Живая проверка 2026-11-10: бот записал «Какой прогноз» делом, владелец нажал «Отменить». Прогноз бот пока не читает
// (источник выберем после сравнения достоверности, docs/DECISIONS.md «Погода (D)», не раньше 2026-11-23), поэтому отвечаем честно.
// С 2026-11-12 есть отдельное уведомление «в Днепре начался дождь» (src/rain.ts): ответ о нём напоминает.
// Правило до разбора напоминания, без языковой модели; промах поправит кнопка «Это было дело» (общая с вопросом про свет).
import { ASK_COMMON, type AskSpec, matchAsk } from "./ask.ts";
import type { MessageBody } from "./discord/types.ts";
import { LIGHT_ASK_BUTTON_PREFIX, LIGHT_ASK_MAX_CHARS } from "./lightAsk.ts";

const FILLER = new Set([
  ...ASK_COMMON,
  "прогноз", "прогноза", "прогнозу", "погода", "погоду", "погоды", "погоде", "погодой", "улице", "улицу", "окном", "за", "днепре", "днепр", "днепра",
  "нужен", "нужно", "надо", "брать", "взять", "одеваться", "одеться", "надеть", "тепло", "холодно", "жарко", "ветер", "ветрено", "температура", "температуры",
  "градусов", "градусах", "неделю", "ближайшие", "дни", "сколько", "зонт", "зонтик", "зонта", "зонтик", "дождь", "дождя", "снег", "снега", "будет", "ли",
]);

/** Сильные слова: «погода», «прогноз», «на улице», «градусов», «температура». */
const KEY = /^(?:погод(?:а|у|ы|е|ой)|прогноз(?:а|у|ом|е)?|температур(?:а|ы|у|ой|е)|градус(?:ов|ах|ы|а)|улиц(?:е|у|а))$/u;
/** Слабые слова (нужно ещё хотя бы одно слово рядом): «будет ли дождь», «зонт брать?», «холодно на улице». */
const WEAK = /^(?:дожд(?:ь|я|ю|ем|е)|снег(?:а|у|ом|е)?|зонт(?:ик|а|у|ом|е)?|холодно|жарко|тепло|ветер|ветрено|мороз|морозно)$/u;

const SPEC: AskSpec = { key: KEY, weakKey: WEAK, filler: FILLER };

/** Похоже ли сообщение на вопрос про погоду. */
export function isWeatherQuestion(text: string): boolean {
  return matchAsk(text, SPEC);
}

/** Честный ответ, пока погода не подключена. Дело из такого запроса не заводится. */
export const WEATHER_REPLY = "Прогноз погоды я пока не читаю: источник ещё не выбран, он будет в утренней сводке. Зато когда в Днепре начнётся дождь, напишу сама (выключается в /settings → «⋯ Ещё»). Дело из вашего вопроса не заводила — если это было дело, нажмите кнопку.";

export function weatherAskMessage(original: string): MessageBody {
  return {
    content: WEATHER_REPLY,
    components: [{ type: 1, components: [{ type: 2, style: 2, label: "Это было дело", custom_id: `${LIGHT_ASK_BUTTON_PREFIX}${original.trim().slice(0, LIGHT_ASK_MAX_CHARS)}` }] }],
    allowed_mentions: { parse: [] },
  };
}
