// «Образы» Хару (пакет «оживление», 2026-11-15): голоса дня поверх настроения движка. ТОЛЬКО ДАННЫЕ и мелкие чистые функции.
// Настроение (tired, tsundere, yandere, sulking, proud, sleepy) считает движок по поведению хозяина и остаётся как есть.
// Образ — это ещё одно звучание для спокойных дней: озорная, чопорная, бодрая. Выбирается случайно по дате (см. day.ts) и никогда
// не перебивает настроение из-за пропусков: цундере после пропуска, яндере-подколки, обида, ночная сонливость остаются.
import type { Mood } from "./moodEngine.ts";

export type Persona = "playful" | "prim" | "bright";
export const PERSONAS: Persona[] = ["playful", "prim", "bright"];
export const isPersona = (v: unknown): v is Persona => typeof v === "string" && (PERSONAS as string[]).includes(v);

/** Чем говорит Хару: настроением движка или образом дня. Ключ пула фраз. */
export type Voice = Mood | Persona;

/**
 * На какое настроение образ похож для аниме-слоя (слова-вставки, знаки, звуки, каомодзи, обращения):
 * озорная и бодрая — как «гордая» (дружелюбные слова), чопорная — без японских слов вовсе (см. `plainRussian`).
 */
export const PERSONA_STYLE: Record<Persona, Mood> = { playful: "proud", prim: "proud", bright: "proud" };
export const styleMood = (v: Voice): Mood => (isPersona(v) ? PERSONA_STYLE[v] : v);
/** Чопорная говорит только по-русски: аниме-слой для неё выключается. */
export const plainRussian = (v: Voice): boolean => v === "prim";

export const PERSONA_LABELS: Record<Persona, string> = {
  playful: "озорная (дразнится по-доброму)",
  prim: "чопорная старшая горничная (холодно-вежливая)",
  bright: "бодрая (сегодня выспалась, и это подозрительно)",
};

