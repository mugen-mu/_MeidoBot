export interface CinemaResult {
  text: string;
  /** обновлённое состояние стиля (с отметкой времени, чтобы выдержать паузу) */
  state: StyleState;
}

/** Кино-момент для ситуации или null. `force` — показать сейчас (для /mood show:cinema), обходит шанс, паузу и уровень. */
export function cinemaMoment(a: {
  mood: Mood;
  situation: Situation;
  style: StyleConfig;
  state: StyleState;
  now: number;
  rand: () => number;
  vars?: { task?: string; user?: string };
  cfg?: MoodConfig;
  force?: boolean;
}): CinemaResult | null {
  const cfg = a.cfg ?? MOOD_CONFIG;
  const kind = KIND[a.situation] ?? (a.force ? "remind" : undefined);
  if (!kind) return null;
  if (!a.force) {
    if (a.style.level < 3) return null;
    if (a.now - (a.state.cin ?? 0) < CINEMA.cooldownHours * 3_600_000) return null;
    if (a.rand() >= CINEMA.chance) return null;
  }
  const list = MONOLOGUES[a.mood][kind];
  const lines = list[Math.min(list.length - 1, Math.floor(a.rand() * list.length))];
  const out: string[] = [];
  for (const l of lines) {
    const m = /^\[sfx:(\w+)\]$/.exec(l);
    if (m) {
      const sfx = SFX[m[1] as SfxId];
      if (sfx && a.style.sfx !== "off") out.push(sfx[a.style.sfx]);
      continue;
    }
    out.push(fill(l, { user: a.vars?.user ?? cfg.address, task: a.vars?.task }, cfg));
  }
  return { text: out.join("\n"), state: { ...a.state, cin: a.now } };
}
