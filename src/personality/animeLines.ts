/** Ночь для «пора спать»: с полуночи до пяти утра по местному времени. Вечер («заварила чай») и раннее утро сюда не входят. */
export const LATE_NIGHT = { from: 0, to: 5 } as const;
export const isLateNight = (hour: number): boolean => hour >= LATE_NIGHT.from && hour < LATE_NIGHT.to;
/** Шанс «пора спать» на ночную отметку серии: не каждый раз, чтобы не стало занудством. */
export const NIGHT_LINE_CHANCE = 0.75;

/**
 * Реплика на отметку: угол по весу, потом фраза в нём. `base` — прежние фразы вида (из core.ts; угол «plain»).
 * Виды, которых здесь нет (списки, карточка, «вопрос недели»), работают как раньше: случайная из `base`.
 */
export function pickReaction(kind: string, base: string[], rand: () => number): string | null {
  const angles = (REACTION_LINES as Record<string, Partial<Record<Angle, string[]>> | undefined>)[kind];
  const weights = (ANGLE_WEIGHT as Record<string, Partial<Record<Angle, number>> | undefined>)[kind];
  const at = (list: string[]): string => list[Math.min(list.length - 1, Math.floor(rand() * list.length))];
  if (!angles || !weights) return base.length ? at(base) : null;
  const options = ANGLE_ORDER.flatMap((angle): [string[], number][] => {
    const list = angle === "plain" ? base : angles[angle];
    const w = weights[angle] ?? 0;
    return list && list.length > 0 && w > 0 ? [[list, w]] : [];
  });
  if (options.length === 0) return base.length ? at(base) : null;
  let x = rand() * options.reduce((sum, [, w]) => sum + w, 0);
  for (const [list, w] of options) {
    x -= w;
    if (x < 0) return at(list);
  }
  return at(options[options.length - 1][0]);
}
