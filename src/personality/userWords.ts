export type UserWordId = "ara_ara" | "ganbatte" | "okaeri" | "yare_yare" | "kawaii";

/** Что считаем словом: сообщение целиком — это слово (с знаками, эмодзи, обращением): «Ара-ара~», «ганбатте, Хару!». */
const WORDS: { id: UserWordId; re: RegExp }[] = [
  { id: "ara_ara", re: /^(?:ара[\s-]*ара|ara[\s-]*ara)$/u },
  { id: "ganbatte", re: /^(?:ганбатте|ганбаре|гамбатте|ganbatte|ganbare)$/u },
  { id: "okaeri", re: /^(?:окаэри|окаири|okaeri)(?:\s+насай)?$/u },
  { id: "yare_yare", re: /^(?:яре[\s-]*яре|yare[\s-]*yare)(?:\s+дзэ)?$/u },
  { id: "kawaii", re: /^(?:кавай|кавайи|kawaii)$/u },
];

/** Имена, которые допустимы после слова («ганбатте, Хару»). */
const NAMES = /^(?:хару|haru|meido|мэйдо|мейдо|горничная|сама|сан|тян)$/u;

/** Слово хозяина или null: берём короткое сообщение, где кроме слова (и, может быть, имени горничной) ничего нет. */
export function detectUserWord(text: string): UserWordId | null {
  const t = text
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\s-]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (!t || t.length > 40) return null;
  const parts = t.split(" ");
  const last = parts[parts.length - 1];
  const head = parts.length > 1 && NAMES.test(last) ? parts.slice(0, -1).join(" ") : t;
  for (const w of WORDS) if (w.re.test(head)) return w.id;
  return null;
}

