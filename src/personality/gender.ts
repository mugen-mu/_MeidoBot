// Хару — девушка: о себе говорит в женском роде («поняла», «записала», «устала»). Проверка на мужской род в её репликах (отзыв Ihor 2026-11-10:
// «иногда писала «понял» и другие глаголы в мужском роде»). Ловим глагол мужского рода без подлежащего (в начале предложения или после «и», «но», запятой:
// «Не понял вас», «Записал») — так Хару говорит о себе; «я … -л» и «я рад/готов». Хозяин — мужчина, и «ты всё-таки сделал» про него верно, поэтому глагол в середине
// предложения после другого подлежащего («никто не сделал», «мой мозг не понял») не трогаем. Лучше отбраковать лишнюю живую реплику (возьмётся готовая), чем оставить ошибку рода.
const VERBS = [
  "понял", "записал", "сделал", "отложил", "удалил", "отменил", "закрыл", "создал", "добавил", "нашёл", "нашел", "забыл", "устал", "решил", "заметил",
  "запомнил", "услышал", "увидел", "прочитал", "проверил", "смог", "хотел", "знал", "думал", "ждал", "разобрал", "принял", "убрал", "поставил", "выбрал",
  "напомнил", "получил", "отправил", "завёл", "завел", "догадался", "ошибся", "старался", "собрался", "согласился", "подумал", "испугался", "обрадовался",
  "растерялся", "задумался", "задремал", "уснул", "проспал", "зевнул", "вздохнул",
];
const START = String.raw`(?:^|[.!?…:;—,]\s*|(?<![\p{L}])(?:и|но|а|да|ведь|зато)\s+|[\p{Extended_Pictographic}️*]\s*)`;
const MASC_VERB = new RegExp(String.raw`${START}(?:(?:ничего|ещё|так и|совсем|просто|даже|тоже|опять|снова)\s+)*(?:не\s+)?(?:${VERBS.join("|")})(?![\p{L}])`, "iu");
/** «я … -л»: «я был», «я не успел» — любое мужское прошедшее после «я». */
const MASC_AFTER_I = /(?<![\p{L}])я\s+(?:(?:не|так|уже|всё|тоже|даже|просто|опять|снова|тут|вот|совсем|очень)\s+)*\p{L}+(?:л|лся)(?![\p{L}])/iu;
/** «я рад/готов/должен» и подобные краткие прилагательные. */
const MASC_ADJ = /(?<![\p{L}])я\s+(?:(?:так|очень|совсем|уже|тоже|даже|просто)\s+)*(?:рад|готов|сам|должен|обязан|вынужден|согласен|уверен|занят|свободен|виноват)(?![\p{L}])/iu;

/** Есть ли в тексте мужской род там, где Хару говорит о себе. */
export function hasMasculineSelf(text: string): boolean {
  return MASC_VERB.test(text) || MASC_AFTER_I.test(text) || MASC_ADJ.test(text);
}
