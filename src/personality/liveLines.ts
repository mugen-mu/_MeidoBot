// ---------- проверка ответа ----------

const THREATS = /(убь[ёеюя]|убить|убива|зарежу|зарезать|задушу|придушу|удавлю|прикончу|расправ|смерт|умр[её]|кровь|кровав|труп|яд[ау]?\b|отравлю|ножом|бить|ударю|искалеч|изувеч)/i;
const EMOJI = /[\p{Extended_Pictographic}️‍]/gu;
const BLOCK_WORDS = /(языков\w+ модел|нейросет|\bии\b|искусственн\w+ интеллект|chatgpt|gemma|openai|claude)/i;

/** Приводит ответ модели к реплике или null. Не бросает исключений. */
export function cleanLine(raw: string, r: Pick<LineRequest, "length">): string | null {
  let t = raw.replace(/\r/g, "").trim();
  // убрать обёртки: кавычки, «Реплика:», код-блоки
  t = t.replace(/^```[a-z]*\n?|```$/gim, "").replace(/^(реплика|ответ)\s*[:—-]\s*/i, "").trim();
  t = t.replace(/^[«"“„'](.*)[»"”'“]$/s, "$1").trim();
  t = t.replace(EMOJI, "").replace(/[ \t]{2,}/g, " ").trim();
  // одна реплика: максимум два абзаца, склеиваем переносами в пробел
  t = t.split(/\n{2,}/)[0].replace(/\s*\n\s*/g, " ").trim();
  if (t.length < 2 || t.length > 260) return null;
  if (/[A-Za-z]/.test(t)) return null; // латиница (английские слова, марки моделей) — не в нашем стиле
  if (!/[А-Яа-яЁёІіЇїЄєҐґ]{2}/.test(t)) return null;
  if (/https?:|www\.|[{}<>\\]|^#|^\s*[-•*]\s|\d{6,}/m.test(t)) return null;
  if (THREATS.test(t) || BLOCK_WORDS.test(t)) return null;
  if (hasMasculineSelf(t)) return null; // Хару — девушка: «понял», «записал» о себе — ошибка рода, возьмётся готовая фраза
  if (detectSecret(t).secret) return null;
  // слишком многословно для запрошенной длины: больше 45 слов — отбраковка (модель «разговорилась»)
  const words = t.split(/\s+/).length;
  if (words > (r.length === "long" ? 45 : r.length === "medium" ? 32 : 20)) return null;
  // звёздочек должно быть чётное число (не больше одной пары)
  const stars = (t.match(/\*/g) ?? []).length;
  if (stars % 2 !== 0 || stars > 4) return null;
  return t;
}

function replyText(out: unknown): string | null {
  const o = out as { response?: unknown; choices?: { message?: { content?: unknown } }[] } | null;
  if (!o || typeof o !== "object") return null;
  const t = o.response ?? o.choices?.[0]?.message?.content;
  return typeof t === "string" && t.trim() ? t : null;
}

/**
 * Реплика от модели или null (любой сбой). Не бросает исключений.
 * Вызывающий отвечает за: настройку «живые реплики», дневной лимит, серьёзные темы и проверку названия дела на секреты.
 */
export async function liveLine(ai: AiBinding | undefined, r: LineRequest, o: { timeoutMs: number; temperature?: number }): Promise<string | null> {
  if (!ai) return null;
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    const call = ai.run(LLM_MODEL, {
      messages: [
        { role: "system", content: buildLinePrompt(r) },
        { role: "user", content: "Реплика:" },
      ],
      max_tokens: r.length === "long" ? 110 : 70,
      temperature: o.temperature ?? 1.0,
      chat_template_kwargs: { enable_thinking: false },
    });
    const timeout = new Promise<null>((resolve) => {
      timer = setTimeout(() => resolve(null), o.timeoutMs);
    });
    const out = await Promise.race([call, timeout]);
    call.catch(() => undefined);
    const text = out === null ? null : replyText(out);
    return text ? cleanLine(text, r) : null;
  } catch {
    return null;
  } finally {
    if (timer) clearTimeout(timer);
  }
}
