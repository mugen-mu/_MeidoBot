/** Слова, которые модели лучше не предлагать (и так звучат часто): «яре яре», «бака», «мо-о». */
const OVERUSED = new Set(["yare_yare", "baka", "mou"]);

/**
 * Несколько японских слов под настроение для одной реплики (без «яре яре», «бака», «мо-о» и токенов): модель берёт их из набора, а не из головы,
 * и у разных реплик набор разный — так слова чередуются. Порядок и выбор зависят только от `rand`.
 */
export function pickJaWords(mood: Mood, rand: () => number, n = 5): string[] {
  const pool = WORDS.filter((w) => w.slot !== "token" && w.moods.includes(mood) && !OVERUSED.has(w.id)).map((w) => w.cyrillic);
  const out: string[] = [];
  while (out.length < n && pool.length) out.push(pool.splice(Math.min(pool.length - 1, Math.floor(rand() * pool.length)), 1)[0]);
  return out;
}

